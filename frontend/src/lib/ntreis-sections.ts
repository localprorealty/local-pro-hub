export type FieldType =
  | 'text'
  | 'number'
  | 'currency'
  | 'textarea'
  | 'select'
  | 'radio'
  | 'multiselect'
  | 'date'
  | 'room_row'
  | 'yes_no'

export interface NtreisField {
  key: string
  label: string
  type: FieldType
  required: boolean
  options?: string[]
  roomFeatures?: string[]
  maxLength?: number
  placeholder?: string
  helpText?: string
  conditionalOn?: { key: string; value: string | string[] }
}

export interface NtreisSection {
  id: number
  name: string
  pdfPages: number[]
  fields: NtreisField[]
}

export interface RoomRowValue {
  room_name?: string
  level?: string
  length?: number | string
  width?: number | string
  features?: string[]
}

export type FormData = Record<string, unknown>

export type SectionStatus = 'complete' | 'partial' | 'empty'


