export function isFieldVisible(field: NtreisField, formData: FormData): boolean {
  if (!field.conditionalOn) return true
  const { key, value } = field.conditionalOn
  const current = formData[key]
  if (Array.isArray(value)) {
    return typeof current === 'string' && value.includes(current)
  }
  return current === value
}

export function isSectionVisible(section: NtreisSection, formData: FormData): boolean {
  if (section.id === 20) {
    const subType = formData.property_sub_type
    return subType === 'Condominium' || subType === 'Townhouse'
  }
  if (section.id === 21) {
    return formData.property_sub_type === 'Farm'
  }
  return true
}

export function isFieldFilled(value: unknown): boolean {
  if (value === undefined || value === null) return false
  if (typeof value === 'string') return value.trim().length > 0
  if (typeof value === 'number') return !Number.isNaN(value)
  if (typeof value === 'boolean') return true
  if (Array.isArray(value)) return value.length > 0
  if (typeof value === 'object') {
    const row = value as RoomRowValue
    const hasLevel = typeof row.level === 'string' && row.level.trim().length > 0
    const hasLength =
      row.length !== undefined &&
      row.length !== null &&
      String(row.length).trim().length > 0
    const hasWidth =
      row.width !== undefined &&
      row.width !== null &&
      String(row.width).trim().length > 0
    const hasFeatures = Array.isArray(row.features) && row.features.length > 0
    return hasLevel || hasLength || hasWidth || hasFeatures
  }
  return false
}

export function getSectionStatus(section: NtreisSection, formData: FormData): SectionStatus {
  const visibleFields = section.fields.filter((field) => isFieldVisible(field, formData))
  const requiredFields = visibleFields.filter((field) => field.required)

  if (requiredFields.length === 0) {
    const anyFilled = visibleFields.some((field) => isFieldFilled(formData[field.key]))
    return anyFilled ? 'complete' : 'empty'
  }

  const filledRequired = requiredFields.filter((field) => isFieldFilled(formData[field.key]))
  if (filledRequired.length === 0) return 'empty'
  if (filledRequired.length === requiredFields.length) return 'complete'
  return 'partial'
}

export function getVisibleSections(formData: FormData): NtreisSection[] {
  return NTREIS_SECTIONS.filter((section) => isSectionVisible(section, formData))
}

export function countRequiredRemaining(sections: NtreisSection[], formData: FormData): number {
  let count = 0
  for (const section of sections) {
    if (!isSectionVisible(section, formData)) continue
    for (const field of section.fields) {
      if (!field.required) continue
      if (!isFieldVisible(field, formData)) continue
      if (!isFieldFilled(formData[field.key])) count += 1
    }
  }
  return count
}
